function is_https(): bool
{
    return (!empty($_SERVER['HTTPS']) && $_SERVER['HTTPS'] !== 'off')
        || (($_SERVER['HTTP_X_FORWARDED_PROTO'] ?? '') === 'https')
        || (($_SERVER['SERVER_PORT'] ?? '') === '443');
}

function app_config(): ?array
{
    static $cfg = null;
    if ($cfg === null && is_file(CONFIG_FILE)) {
        $cfg = require CONFIG_FILE;
    }
    return $cfg;
}

function write_config(array $cfg): void
{
    if (!is_dir(DATA_DIR) && !mkdir(DATA_DIR, 0750, true)) {
        throw new RuntimeException('Could not create the data folder. Check folder permissions.');
    }
    $php = "<?php\n// Generated by Previously Noted setup. Keep this file private.\nreturn " . var_export($cfg, true) . ";\n";
    if (file_put_contents(CONFIG_FILE, $php, LOCK_EX) === false) {
        throw new RuntimeException('Could not write data/config.php. Check folder permissions.');
    }
    @chmod(CONFIG_FILE, 0640);
}

function start_session(): void
{
    if (session_status() === PHP_SESSION_ACTIVE) {
        return;
    }
    $path = rtrim(str_replace('\\', '/', dirname($_SERVER['SCRIPT_NAME'] ?? '/')), '/') . '/';
    session_name('prevnoted');
    session_set_cookie_params([
        'lifetime' => 60 * 60 * 24 * 14,
        'path' => $path,
        'httponly' => true,
        'samesite' => 'Lax',
        'secure' => is_https(),
    ]);
    ini_set('session.gc_maxlifetime', (string)(60 * 60 * 24 * 14));
    session_start();
    if (empty($_SESSION['csrf'])) {
        $_SESSION['csrf'] = bin2hex(random_bytes(32));
    }
}

