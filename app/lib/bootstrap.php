const CATEGORY_COLORS = ['tag-e', 'tag-n', 'tag-a', 'cat-green', 'cat-red', 'cat-teal', 'cat-pink', 'cat-olive', 'cat-sand', 'cat-gray'];
const DEFAULT_CATEGORIES = [
    ['E', 'Edit', 'tag-e', 'picture'],
    ['N', 'Narration', 'tag-n', 'narration'],
    ['A', 'Graphics', 'tag-a', 'picture'],
];

/** A film's note tracks, in order. Every film starts with Edit, Narration and Graphics. */
function film_categories(int $filmId): array
{
    $st = db()->prepare('SELECT id, key, label, color, kind, sort FROM categories WHERE film_id = ? ORDER BY sort, id');
    $st->execute([$filmId]);
    $rows = $st->fetchAll();
    if (!$rows) {
        $ins = db()->prepare('INSERT OR IGNORE INTO categories (film_id, key, label, color, kind, sort) VALUES (?,?,?,?,?,?)');
        foreach (DEFAULT_CATEGORIES as $i => [$k, $l, $c, $kind]) {
            $ins->execute([$filmId, $k, $l, $c, $kind, $i]);
        }
        $st->execute([$filmId]);
        $rows = $st->fetchAll();
    }
    return array_map(fn($r) => ['id' => (int)$r['id'], 'sort' => (int)$r['sort']] + $r, $rows);
}

function film_keys(int $filmId): array
{
    return array_column(film_categories($filmId), 'key');
}

/**
 * Parse the director's track prefix: "E: …", "N - …", "E-N: …", "N _ …", or any track key the film has ("M: …").
 */
function split_tag(string $text, array $keys = ['E', 'N', 'A']): array
{
    $keys = array_values(array_filter($keys, fn($k) => $k !== ''));
    if ($keys) {
        usort($keys, fn($a, $b) => strlen($b) <=> strlen($a));
        $alt = implode('|', array_map(fn($k) => preg_quote($k, '/'), $keys));
        // A numbered item ("ARCH-001 : …", "VFX_012 …") or the code on its own ("CG"): the track is the code,
        // and the text keeps the number, which people refer to.
        if (preg_match('/^\s*(' . $alt . ')(?:[-_ ]?\d{1,5}[A-Z]?\b|\s*$)/', $text, $m)) {
            return [$m[1], trim($text)];
        }
        if (preg_match('/^\s*((?:' . $alt . ')(?:\s*[-\/]\s*(?:' . $alt . '))*)\s*[:\-_]\s*(.*)$/s', $text, $m)) {
            $tag = str_replace('/', '-', preg_replace('/\s+/', '', $m[1]));
            return [$tag, trim($m[2])];
        }
    }
    return ['', trim($text)];
}

/**
 * Codes that comments start with, which the film has no track for yet: numbered items like "ARCH-001",
 * "VFX_12", or a code with a colon or on its own ("CG:", "CG"). Returns [code => count], most used first.
 */
const CODE_STOPWORDS = ['OK', 'NO', 'YES', 'THE', 'AND', 'FOR', 'NOT', 'BUT', 'ALL', 'WE', 'IS', 'IT', 'TO', 'OF', 'IN', 'ON', 'AT', 'BE',
    'DO', 'SO', 'OR', 'IF', 'MY', 'ME', 'HE', 'US', 'UP', 'TC', 'NB', 'PS', 'FYI', 'ASAP', 'LOL', 'HI', 'THIS', 'THAT', 'WHY', 'HOW', 'WHAT'];
function detect_codes(array $texts, array $keys): array
{
    $seen = [];
    $strong = [];
    foreach ($texts as $t) {
        if (!preg_match('/^\s*([A-Z][A-Z0-9]{1,7})(?:([-_ ]\d{1,5}[A-Z]?)\b|\s*([:\x{2013}\x{2014}-])|\s*$)/u', (string)$t, $m)) {
            continue;
        }
        $code = $m[1];
        if (in_array($code, $keys, true) || in_array($code, CODE_STOPWORDS, true) || preg_match('/^\d/', $code)) {
            continue;
        }
        $seen[$code] = ($seen[$code] ?? 0) + 1;
        if (($m[2] ?? '') !== '') {
            $strong[$code] = true; // a numbered item like ARCH-001 is a code even if it appears once
        }
    }
    // Numbered codes count from one note; "CODE:" or the code on its own needs at least two.
    $out = array_filter($seen, fn($n, $c) => isset($strong[$c]) || $n >= 2, ARRAY_FILTER_USE_BOTH);
    arsort($out);
    return $out;
}

