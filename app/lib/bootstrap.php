/** Keep only track keys the film has; '' means untagged. */
function clean_tag(string $tag, array $keys): string
{
    $parts = array_values(array_unique(array_filter(array_map('trim', explode('-', strtoupper($tag))), fn($p) => in_array($p, $keys, true))));
    return implode('-', $parts);
}

function tc_to_frames(string $tc, int $base): ?int
{
    if (!preg_match('/^(\d{1,2})[:;](\d{2})[:;](\d{2})[:;.](\d{2})$/', trim($tc), $m)) {
        return null;
    }
    return ((((int)$m[1] * 60) + (int)$m[2]) * 60 + (int)$m[3]) * $base + (int)$m[4];
}

function frames_to_tc(int $f, int $base): string
{
    $ff = $f % $base;
    $s = intdiv($f, $base);
    return sprintf('%02d:%02d:%02d:%02d', intdiv($s, 3600), intdiv($s, 60) % 60, $s % 60, $ff);
}

function current_status(int $noteId): string
{
    $st = db()->prepare('SELECT status FROM events WHERE note_id = ? ORDER BY id DESC LIMIT 1');
    $st->execute([$noteId]);
    return $st->fetchColumn() ?: 'open';
}

function add_event(int $noteId, ?int $versionId, string $status, ?string $comment, string $by): void
{
    if (!in_array($status, STATUSES, true)) {
        fail('Unknown status.');
    }
    db()->prepare('INSERT INTO events (note_id, version_id, status, comment, by_name, at) VALUES (?,?,?,?,?,?)')
        ->execute([$noteId, $versionId, $status, $comment !== '' ? $comment : null, $by, now_iso()]);
}
